"""Write benchmark/: a PILOT ratings set (prompts, blind human ratings, product ids only) from tracked run files.
Reads only: runs/judge-validate.jsonl (test 4), runs/judge-test5.jsonl (test 5), runs/claude-plans.jsonl (test 4 prompt texts).
Test 5 prompt texts are not tracked: pass --prompts FILE (one per line, e.g. data/human_prompts_test5.txt) to include them.
No titles, photos, paths or names are ever written. Product ids are written as strings. Nothing is published by this script.
Usage: .venv/bin/python scripts/make_pilot_ratings_set.py [--out benchmark] [--prompts FILE]"""
import argparse, json, pathlib

ap = argparse.ArgumentParser()
ap.add_argument("--out", default="benchmark")
ap.add_argument("--runs", default="runs")
ap.add_argument("--prompts", default=None, help="test 5 prompt texts, one per line, in order 1..50 (lines starting # are skipped)")
a = ap.parse_args()
RUNS = pathlib.Path(a.runs)
OUT = pathlib.Path(a.out)


def jl(path):
    return [json.loads(l) for l in open(path) if l.strip()]


SETS = {  # test_set -> (ratings file, method letters as written in that file's blind-test summary)
    "test4": ("judge-validate.jsonl", {"A": "raw sentence, general catalogue only", "B": "raw sentence, all four catalogues", "C": "understood plan, all four catalogues"}),
    "test5": ("judge-test5.jsonl", {"B": "raw sentence, all four catalogues", "C": "local Qwen3 plan", "D": "Claude Sonnet 5.5 plan"}),
}

t4_text = {r["n"]: r["prompt"] for r in jl(RUNS / "claude-plans.jsonl")}
t5_text = {}
if a.prompts:
    lines = [l.strip() for l in open(a.prompts, encoding="utf-8") if l.strip() and not l.startswith("#")]
    t5_text = {i + 1: t for i, t in enumerate(lines)}

ratings, prompt_ids = [], {"test4": set(), "test5": set()}
for ts, (fname, _) in SETS.items():
    for r in jl(RUNS / fname):
        pid = f"{ts}-p{int(r['n']):02d}"
        prompt_ids[ts].add(int(r["n"]))
        ids = [str(x) for piece in r["rows"] for x in piece]
        ratings.append({"prompt_id": pid, "test_set": ts, "method": r["method"], "rating": r["human"], "product_ids": ids})

prompts = []
for ts, src, texts in (("test4", "author", t4_text), ("test5", "llm-generated", t5_text)):
    for n in sorted(prompt_ids[ts]):
        prompts.append({"id": f"{ts}-p{n:02d}", "test_set": ts, "text": texts.get(n), "source": src})

OUT.mkdir(parents=True, exist_ok=True)
for name, recs in (("prompts.jsonl", prompts), ("ratings.jsonl", ratings)):
    (OUT / name).write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in recs), encoding="utf-8")

n4 = sum(r["test_set"] == "test4" for r in ratings)
n5 = sum(r["test_set"] == "test5" for r in ratings)
t5_note = ("Test 5 prompt texts are included (from --prompts)." if t5_text else
           "Test 5 prompt texts are left empty (null): they are not in tracked files. Re-run with --prompts to add them.")
README = f"""# Pilot ratings set (not a benchmark)

This is a small pilot set of blind human ratings of outfit search results.
It is a by-product of one project. It is too small and too narrow to rank systems.
Nothing here has been published. See LICENSE-NOTE.md first.

## What is in it

- `prompts.jsonl`: {len(prompts)} shopper requests ({len(prompt_ids['test4'])} from test 4, {len(prompt_ids['test5'])} from test 5). Keys: id, test_set, text, source.
- `ratings.jsonl`: {len(ratings)} rated options ({n4} from test 4, {n5} from test 5). Keys: prompt_id, test_set, method, rating, product_ids.
- Product ids are strings. They point into third-party product datasets. No titles, photos or paths are included.
- `product_ids` lists the products shown for one option, piece by piece, flattened in order.

## Scale and method letters

- Rating is `good` (2), `okay` (1) or `bad` (0). One person rated each option, blind to the method.
- Test 4 methods: A = {SETS['test4'][1]['A']}; B = {SETS['test4'][1]['B']}; C = {SETS['test4'][1]['C']}.
- Test 5 methods: B = {SETS['test5'][1]['B']}; C = {SETS['test5'][1]['C']}; D = {SETS['test5'][1]['D']}.
- Identical options from several methods were shown once. They carry the first method listed for them.
- Letters are the answer-key letters from runs/blind-test4.summary.json and runs/blind-test5.summary.json.

## Prompts

- Test 4 prompts: the project owner wrote them, per the test 4 summary. Source is `author`.
- Test 5 prompts: 50 fresh requests generated by a language model for this project (the project's own notes say so; no tracked file records it). Source is `llm-generated`.
- {t5_note}

## Caveats

- One rater, who also wrote the test 4 prompts. No agreement between people is measured.
- Both test sets were used once for the project's own evaluation. They are no longer fresh.
- The prompts are Indian-occasion requests. Results may not carry over to other markets.
- Ratings judge whole outfit options. They are not relevance labels for single products.
- Product ids were read from run logs. Some ids come from sets with their own licence terms.

## How to cite

Cite as: "Lucida pilot ratings set (single rater, 2 test sets), project repository, {n4 + n5} ratings."
Add the repository address and commit once it is published. Do not call it a benchmark.

Regenerate: `.venv/bin/python scripts/make_pilot_ratings_set.py [--prompts data/human_prompts_test5.txt]`
"""
LICENSE = """# Licence note (proposal only)

Nothing in this folder has been published. This note is a proposal, not a grant.

- Proposed licence for the prompts and the ratings: CC-BY-4.0.
- Product ids refer to third-party datasets. Those datasets have their own terms. This licence does not cover them.
- No product photos and no product titles are included here.
- The owner must verify the terms of each dataset before publishing. The Marqo data comes from Google Shopping.
- The Myntra and men's-set data have licence caveats listed in the project README.
- The owner must also check the employer and university policies on side projects.

Until those checks are done, keep this folder out of any public repository.
"""
(OUT / "README.md").write_text(README, encoding="utf-8")
(OUT / "LICENSE-NOTE.md").write_text(LICENSE, encoding="utf-8")
print(f"wrote {OUT}/: {len(prompts)} prompts, {len(ratings)} ratings ({n4} test4, {n5} test5)")
